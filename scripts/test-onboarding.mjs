import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'rolldown';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'companion-setup-'));
await build({ input: ['src/onboarding.ts', 'src/store.ts'], platform: 'node', logLevel: 'silent', output: {dir:temp,format:'esm',entryFileNames:'[name].mjs'} });
const { newSetup, completeSetup, nextDailyTime, setupFor, needsSetup } = await import(pathToFileURL(path.join(temp,'onboarding.mjs')));
const { emptyData } = await import(pathToFileURL(path.join(temp,'store.mjs')));
const fresh = emptyData(), now = new Date(2026,9,24,18,0,0);
assert.equal(needsSetup(fresh),true);
const draft=newSetup(fresh);
assert.equal(draft.step,'name');assert.equal(draft.waterMins,0);assert.equal(draft.movementMins,0);assert.equal(draft.bedtime,null);
assert.deepEqual(draft.times,{meditation:null,meal:null,coffee:null});
const legacy={...fresh,settings:{...fresh.settings,welcomed:true}};
assert.equal(needsSetup(legacy),true,'legacy mic hello must not count as full setup');
fresh.todos.push({id:'old',text:'A personal reminder',done:false,due:'2026-10-23T12:00:00.000Z',createdAt:now.toISOString()});
fresh.setup={...draft,step:'meal',name:'Pepper',waterMins:45,times:{meditation:'17:00',meal:'13:00',coffee:'19:00'}};
assert.deepEqual(setupFor(structuredClone(fresh)),fresh.setup,'resume exact unfinished choices');
assert.equal(fresh.todos.length,1,'draft never creates a task');
assert.equal(fresh.settings.onboardingVersion,0);
const done=completeSetup(fresh,{...fresh.setup,bedtime:'17:00'},now);
assert.equal(needsSetup(done),false);assert.equal(done.setup,undefined);assert.equal(done.settings.companionName,'Pepper');
assert.equal(done.settings.waterMins,45);assert.equal(done.settings.waterNudge,true);
assert.deepEqual(done.todos[0],fresh.todos[0],'existing personal task untouched');
assert.equal(done.wellness.bedtimeDate,done.wellness.date,'no immediate late-evening bedtime alert');
for(const t of done.todos.filter(t=>t.wellnessKind)) {assert.ok(new Date(t.due)>now);assert.equal(t.recurring,'daily');}
assert.equal(new Date(done.todos.find(t=>t.wellnessKind==='meditation').due).getDate(),25);
assert.equal(new Date(done.todos.find(t=>t.wellnessKind==='coffee').due).getDate(),24);
const again=completeSetup(done,{...newSetup(done),times:{meditation:'18:00',meal:null,coffee:null}},now);
assert.equal(again.todos.filter(t=>t.wellnessKind).length,1,'review replaces only setup-owned active reminders, without duplicates');
assert.deepEqual(again.todos[0],fresh.todos[0]);
assert.ok(nextDailyTime('18:00',now)>now,'equal time starts tomorrow');
assert.equal(nextDailyTime('10:00',new Date(2026,11,31,23)).getFullYear(),2027);
assert.throws(()=>nextDailyTime('24:00',now));assert.throws(()=>nextDailyTime('',now));
assert.equal(fresh.settings.onboardingVersion,0,'applying returns a new object');
console.log('PASS: opt-in fresh setup, legacy upgrade, resumable draft, future-only daily schedules, bedtime, preserved tasks, no duplicate care reminders, invalid times.');
