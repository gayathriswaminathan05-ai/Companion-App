// Run after building gallery.html to /tmp/companion-gallery-v2 (see session notes).
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const out = path.resolve('docs/qa/2026-10-16');
app.whenReady().then(async () => {
  app.dock?.hide();
  const win = new BrowserWindow({ width: 1280, height: 900, show: false, webPreferences: { offscreen: true, backgroundThrottling: false } });
  win.webContents.setAudioMuted(true); // verify playback without interrupting the owner
  const js = code => win.webContents.executeJavaScript(code);
  const shot = async name => fs.writeFileSync(path.join(out, `${name}.png`), (await win.webContents.capturePage()).toPNG());
  try {
    await win.loadFile('/tmp/companion-gallery-v2/gallery.html');
    await wait(400);
    await js(`window.frame = label => [...document.querySelectorAll('figure')].find(el => el.querySelector('figcaption')?.textContent === label);
      window.press = (label, text) => [...frame(label).querySelectorAll('button')].find(b => b.textContent === text).click();
      window.breathText = () => frame('Breathe: one quiet minute').textContent; void 0;`);
    await shot('app-panels-ready');
    await js("press('Chat: empty', 'Help me start')");
    assert.equal(await js("frame('Chat: empty').querySelector('textarea').value"), 'Help me start');
    assert.match(await js("frame('Chat: empty').textContent"), /Choose a starter/);
    assert.equal(await js("frame('Chat: switched off').querySelectorAll('textarea').length"), 0);
    await js("press('Breathe: one quiet minute','Set a reminder')");
    await wait(100);
    await shot('meditation-reminder-form');
    await js("window.reminderTime = frame('Breathe: one quiet minute').querySelector('input[type=datetime-local]'); window.setTime = value => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(reminderTime,value); reminderTime.dispatchEvent(new Event('input',{bubbles:true})); }; setTime('2020-01-01T10:00'); void 0;");
    await js("press('Breathe: one quiet minute','Set reminder')");
    await wait(100);
    assert.match(await js('breathText()'), /Choose a time in the future/);
    await js("setTime('2099-01-01T10:00'); frame('Breathe: one quiet minute').querySelector('input[type=checkbox]').click(); void 0;");
    await js("press('Breathe: one quiet minute','Set reminder')");
    await wait(100);
    assert.match(await js('breathText()'), /Daily reminder set/);
    assert.match(await js("frame('Tasks').textContent"), /Meditation break/);
    await js("press('Breathe: one quiet minute','Start one minute')");
    await wait(5600);
    assert.equal(await js("frame('Breathe: one quiet minute').querySelector('audio').paused"), false);
    assert.ok(await js("frame('Breathe: one quiet minute').querySelector('audio').currentTime > 5"));
    assert.equal(await js("frame('Breathe: one quiet minute').querySelector('audio').muted"), false);
    assert.match(await js("frame('Breathe: one quiet minute').querySelector('audio').currentSrc"), /guided-v2/);
    assert.equal(await js("frame('Breathe: one quiet minute').querySelectorAll('audio')[1].paused"), false, 'music plays with guide');
    assert.equal(await js("frame('Breathe: one quiet minute').querySelectorAll('audio')[1].volume"), 0.25, 'music begins quietly');
    assert.ok(await js("Math.abs(frame('Breathe: one quiet minute').querySelectorAll('audio')[1].currentTime - frame('Breathe: one quiet minute').querySelector('audio').currentTime) < 0.4"), 'music stays with guide');
    assert.match(await js('breathText()'), /Breathe in gently/);
    await shot('app-breathing-active');
    await js("press('Breathe: one quiet minute','Pause')");
    await wait(200);
    const paused = await js('breathText()');
    const audioPausedAt = await js("frame('Breathe: one quiet minute').querySelector('audio').currentTime");
    await wait(1500);
    assert.equal(await js('breathText()'), paused, 'pause freezes remaining time');
    assert.equal(await js("frame('Breathe: one quiet minute').querySelector('audio').currentTime"), audioPausedAt, 'pause stops voice too');
    assert.equal(await js("frame('Breathe: one quiet minute').querySelectorAll('audio')[1].paused"), true, 'pause stops music too');
    await js("const select = frame('Breathe: one quiet minute').querySelector('select'); select.value='v1'; select.dispatchEvent(new Event('change',{bubbles:true})); void 0;");
    await js("frame('Breathe: one quiet minute').querySelector('input').click(); press('Breathe: one quiet minute','Resume')");
    await wait(300);
    assert.match(await js('breathText()'), /Breathe naturally/);
    assert.match(await js("frame('Breathe: one quiet minute').querySelector('audio').currentSrc"), /ownPace/);
    assert.match(await js("frame('Breathe: one quiet minute').querySelector('audio').currentSrc"), /v1/, 'original voice remains available');
    await js("frame('Breathe: one quiet minute').querySelectorAll('input')[2].click()");
    await wait(100);
    assert.equal(await js("frame('Breathe: one quiet minute').querySelectorAll('audio')[1].muted"), true, 'music mutes independently');
    assert.equal(await js("frame('Breathe: one quiet minute').querySelector('audio').muted"), false, 'music toggle leaves voice on');
    await js("frame('Breathe: one quiet minute').querySelectorAll('input')[1].click()");
    await wait(100);
    assert.equal(await js("frame('Breathe: one quiet minute').querySelector('audio').muted"), true, 'voice toggle mutes immediately');
    console.log('Chat draft-only starters, chat-off state, breathing start, pause and own-pace resume passed. Waiting for full session completion.');
    await wait(55000);
    assert.match(await js('breathText()'), /A little room for you/);
    await shot('app-breathing-complete');
    await js("press('Breathe: one quiet minute','Another minute')");
    await wait(300);
    assert.match(await js('breathText()'), /60s/);
    await js("press('Breathe: one quiet minute','Pause')");
    await js("press('Breathe: one quiet minute','Resume')");
    await wait(200);
    await js("press('Breathe: one quiet minute','Stop')");
    assert.equal(await js("frame('Breathe: one quiet minute').querySelector('audio').paused"), true, 'Stop immediately stops audio');
    assert.equal(await js("frame('Breathe: one quiet minute').querySelectorAll('audio')[1].paused"), true, 'Stop immediately stops music');
    await js("[...document.querySelectorAll('button')].find(b=>b.textContent==='Dark').click()");
    await wait(250);
    const colors = await js("['Quick nav (panel open, chat active)', 'Menu bar (click plant)'].map(label => { const b=frame(label).querySelector('button[aria-label=tasks]'); const s=getComputedStyle(b); return {color:s.color, background:s.backgroundColor}; })");
    const luminance = str => {
      const rgb = str.match(/[\d.]+/g).slice(0,3).map(Number).map(v => v/255 <= 0.04045 ? v/255/12.92 : ((v/255+0.055)/1.055)**2.4);
      return rgb[0]*0.2126+rgb[1]*0.7152+rgb[2]*0.0722;
    };
    for (const {color,background} of colors) {
      const ratio=(luminance(color)+0.05)/(luminance(background)+0.05);
      assert.ok(ratio>=4.5, `dark nav contrast ${ratio}`);
      console.log(`Dark navigation icon contrast: ${ratio.toFixed(2)}:1`);
    }
    await js("frame('Quick nav (panel open, chat active)').scrollIntoView({block:'center'})");
    await shot('dark-navigation-readable');
    fs.writeFileSync(path.join(out,'app-checks.txt'), 'PASS: reminder rejects past dates and creates a daily Meditation break task; dark menu/quick-nav icons exceed 4.5:1 contrast; chat starters draft without sending; chat-off state; soft voice plays and matches inhale cue; music plays quietly in sync; pause freezes both tracks/time; original voice remains available; own-pace resume; independent music/voice mute; full 60-second completion; restart; Stop silences both.\n');
    console.log('Full breathing completion and restart passed.');
    app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
