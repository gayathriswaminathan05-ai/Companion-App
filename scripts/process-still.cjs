// Key a single PNG still into public/character/<state>/ (one frame) + refresh sprites.
// Usage: CLIP_T=15 CLIP_GLOBAL=off node scripts/process-still.cjs <image.png> <stateName>
const { spawnSync } = require("child_process");
const path = require("path");
const fs = require("fs");
const os = require("os");

const [, , input, state] = process.argv;
if (!input || !state) {
  console.error("usage: node scripts/process-still.cjs <image.png> <state>");
  process.exit(1);
}

const root = path.join(__dirname, "..");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "still-"));
const outDir = path.join(root, "public", "character", state);
const src = path.resolve(input);
fs.copyFileSync(src, path.join(tmp, "raw-001.png"));

console.log("1/2 removing background + cropping…");
fs.rmSync(outDir, { recursive: true, force: true });
const electronBin = path.join(root, "node_modules", ".bin", "electron");
const env = { ...process.env, CLIP_IN: tmp, CLIP_OUT: outDir, CLIP_STATE: state };
delete env.ELECTRON_RUN_AS_NODE;
const res = spawnSync(electronBin, [path.join(__dirname, "clip-key.cjs")], {
  env,
  encoding: "utf8",
});
const done = /FRAMES_WRITTEN:(\d+)/.exec(res.stdout + res.stderr);
if (!done) {
  console.error(res.stdout, res.stderr);
  process.exit(1);
}
console.log("   " + done[1] + " frame -> public/character/" + state);

console.log("2/2 regenerating sprite manifest…");
const charDir = path.join(root, "public", "character");
const states = fs
  .readdirSync(charDir)
  .filter((d) => fs.statSync(path.join(charDir, d)).isDirectory());
const oneshot = new Set(["celebrating", "sleeping", "laughing", "meeting"]);
const holdLast = new Set(["sleeping"]);
const fast = new Set(["laughing"]);
const manifest = {};
for (const s of states) {
  const frames = fs.readdirSync(path.join(charDir, s)).filter((f) => f.endsWith(".png")).sort();
  manifest[s] = {
    frames: frames.map((f) => `./character/${s}/${f}`),
    fps: fast.has(s) ? 18 : 12,
    pingpong: !oneshot.has(s) && frames.length > 1,
  };
  if (holdLast.has(s)) manifest[s].holdLast = true;
  const metaFile = path.join(charDir, s, "meta.json");
  if (fs.existsSync(metaFile)) {
    const { srcW, srcH } = JSON.parse(fs.readFileSync(metaFile, "utf8"));
    manifest[s].srcW = srcW;
    manifest[s].srcH = srcH;
  }
}
const ts =
  "// AUTO-GENERATED by scripts/process-clip.cjs — do not edit by hand.\n" +
  "export interface SpriteAnim { frames: string[]; fps: number; pingpong: boolean; holdLast?: boolean; srcW?: number; srcH?: number }\n" +
  "export const SPRITES: Record<string, SpriteAnim> = " +
  JSON.stringify(manifest, null, 2) +
  ";\n";
fs.mkdirSync(path.join(root, "src", "generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src", "generated", "sprites.ts"), ts);
fs.rmSync(tmp, { recursive: true, force: true });
console.log("done ✓");
